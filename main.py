import streamlit as st
import pandas as pd


# ============================================================
# 기본 설정
# ============================================================

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide"
)

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")
st.write(
    "영화 데이터를 시간의 흐름에 따라 그래프로 살펴보는 도감입니다."
)


# ============================================================
# 데이터 불러오기
# ============================================================

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/modudata/"
    "main/data/kobis_daily.csv"
)


@st.cache_data
def load_data():
    """CSV 파일을 불러오고 날짜와 숫자 데이터를 정리합니다."""

    # GitHub에 있는 CSV 파일을 읽습니다.
    df = pd.read_csv(
        DATA_URL,
        encoding="utf-8-sig"
    )

    # --------------------------------------------------------
    # 날짜를 진짜 날짜(datetime) 형식으로 변환
    # 예: 20250901 → 2025-09-01
    # --------------------------------------------------------

    df["날짜"] = pd.to_datetime(
        df["날짜"].astype(str),
        format="%Y%m%d",
        errors="coerce"
    )

    # --------------------------------------------------------
    # 숫자로 사용해야 하는 열을 숫자형으로 변환
    # --------------------------------------------------------

    number_columns = [
        "순위",
        "영화코드",
        "일관객",
        "누적관객",
        "스크린수",
        "상영횟수"
    ]

    for column in number_columns:
        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )

    # 날짜나 영화명이 없는 행은 제외합니다.
    df = df.dropna(
        subset=["날짜", "영화명"]
    )

    return df


df = load_data()


# ============================================================
# 그래프 1
# 영화별 일관객 변화
# ============================================================

st.divider()

st.header("📈 그래프 1. 영화별 일관객 변화")

st.write(
    "영화를 하나 선택하면 날짜에 따른 일관객 변화를 볼 수 있습니다."
)


# ------------------------------------------------------------
# 영화 선택 드롭다운
# ------------------------------------------------------------

# 영화 이름을 가나다순으로 정리합니다.
movie_list = sorted(
    df["영화명"].unique()
)


selected_movie = st.selectbox(
    "영화를 선택하세요",
    movie_list
)


# ------------------------------------------------------------
# 선택한 영화의 데이터만 추출
# ------------------------------------------------------------

movie_df = df[
    df["영화명"] == selected_movie
].copy()


# 날짜순으로 정렬합니다.
movie_df = movie_df.sort_values(
    "날짜"
)


# ------------------------------------------------------------
# 그래프용 데이터 만들기
# ------------------------------------------------------------

chart_data = movie_df[
    ["날짜", "일관객"]
].set_index("날짜")


# ------------------------------------------------------------
# 선 그래프
# ------------------------------------------------------------

st.line_chart(
    chart_data,
    y="일관객",
    x_label="날짜",
    y_label="일관객 (명)",
    use_container_width=True
)


# ------------------------------------------------------------
# 그래프 설명 자리
# ------------------------------------------------------------

st.markdown("### 💡 이 그래프로 알 수 있는 것")

st.info(
    "이 그래프로 알 수 있는 것: "
    "선택한 영화의 날짜별 일관객 변화를 확인할 수 있습니다."
)


